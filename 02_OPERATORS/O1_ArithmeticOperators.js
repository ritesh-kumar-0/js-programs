// Operators are symbols used to perform operations on values.
//Arithmetic Operators
let a = 10;
let b = 3;

console.log(a + b);  // 13
console.log(a - b);  // 7
console.log(a * b);  // 30
console.log(a / b);  // 3.333...
console.log(a % b);  // 1  , % gives the remainder
console.log(a ** b); // 1000